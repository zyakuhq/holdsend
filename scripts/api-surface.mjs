// Records the public TypeScript API of every package entry point and fails
// when it changes without the record being updated.
//
//   node scripts/api-surface.mjs            (after npm run build) check
//   node scripts/api-surface.mjs --update   rewrite api/*.api.txt
//
// For each entry point in a package's "exports", the record lists every
// exported name with its declaration as the compiler emitted it (comments
// removed), followed by every type those declarations refer to that is not
// exported itself, since changing those changes the API too. A change to the
// record is a change to the public API: review it as one. Before 1.0 such
// changes are allowed; after 1.0 they need a major version (decision 0012).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const PACKAGES = ["core", "server", "web", "react-native"];
const OUT_DIR = join(ROOT, "api");
const update = process.argv.includes("--update");

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

function entriesOf(dir) {
  const pkg = JSON.parse(readFileSync(join(ROOT, "packages", dir, "package.json"), "utf8"));
  const entries = [];
  for (const [subpath, target] of Object.entries(pkg.exports ?? {})) {
    if (typeof target !== "object" || !target.types) continue;
    const name = subpath === "." ? pkg.name : `${pkg.name}/${subpath.slice(2)}`;
    entries.push({ name, file: join(ROOT, "packages", dir, target.types) });
  }
  return { pkgName: pkg.name, entries };
}

function isOurs(file) {
  const rel = relative(ROOT, file).split(sep).join("/");
  return /^packages\/[^/]+\/dist\//.test(rel);
}

function print(node) {
  return printer.printNode(ts.EmitHint.Unspecified, node, ts.getOriginalNode(node).getSourceFile()).trim();
}

// The declaration text for one symbol, without "export"/"declare" noise that
// depends on how the file re-exports it.
function declarationText(decl) {
  if (ts.isClassDeclaration(decl)) {
    const isPrivate = (m) => m.modifiers?.some((x) => x.kind === ts.SyntaxKind.PrivateKeyword) || (m.name && ts.isPrivateIdentifier(m.name));
    decl = ts.factory.updateClassDeclaration(decl, decl.modifiers, decl.name, decl.typeParameters, decl.heritageClauses, decl.members.filter((m) => !isPrivate(m)));
  }
  let text = print(decl);
  text = text.replace(/^export (default )?/, "").replace(/^declare /, "");
  return text;
}

// Types named inside a declaration that resolve to one of our .d.ts files.
function referencedSymbols(checker, decl) {
  const found = [];
  const visit = (node) => {
    let target;
    if (ts.isTypeReferenceNode(node)) target = node.typeName;
    else if (ts.isExpressionWithTypeArguments(node)) target = node.expression;
    else if (ts.isTypeQueryNode(node)) target = node.exprName;
    if (target) {
      let sym = checker.getSymbolAtLocation(target);
      if (sym && sym.flags & ts.SymbolFlags.Alias) sym = checker.getAliasedSymbol(sym);
      if (sym && !(sym.flags & ts.SymbolFlags.TypeParameter) && sym.declarations?.some((d) => isOurs(d.getSourceFile().fileName))) found.push(sym);
    }
    ts.forEachChild(node, visit);
  };
  visit(decl);
  return found;
}

const keyOf = (sym) => `${sym.declarations?.[0]?.getSourceFile().fileName}#${sym.getName()}`;

// Every symbol some entry point of some package exports: those are listed
// under their own entry, so other records only name them.
function allExportedKeys(program, files) {
  const checker = program.getTypeChecker();
  const keys = new Set();
  for (const file of files) {
    const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(file));
    for (const sym of moduleSymbol ? checker.getExportsOfModule(moduleSymbol) : []) {
      keys.add(keyOf(sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym));
    }
  }
  return keys;
}

function surface(entry, program, publicKeys) {
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entry.file);
  if (!source) throw new Error(`${entry.file} is missing. Run "npm run build" first.`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  const exportsList = moduleSymbol ? checker.getExportsOfModule(moduleSymbol) : [];

  const exported = new Map();
  for (const sym of exportsList) {
    const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    exported.set(sym.getName(), target);
  }
  const exportedTargets = new Set(exported.values());

  const lines = [`// ${entry.name}`, "// Generated by scripts/api-surface.mjs. Do not edit by hand.", ""];
  const queue = [];
  for (const name of [...exported.keys()].sort()) {
    const target = exported.get(name);
    const decls = (target.declarations ?? []).filter((d) => !ts.isSourceFile(d));
    if (decls.length === 0) {
      lines.push(`// ${name}: ${checker.typeToString(checker.getTypeOfSymbol(target))}`, "");
      continue;
    }
    lines.push(`// ${name}${target.getName() !== name ? ` (as ${target.getName()})` : ""}`);
    for (const decl of decls) {
      lines.push(declarationText(decl));
      queue.push(...referencedSymbols(checker, decl));
    }
    lines.push("");
  }

  // Types reached from the exported ones but not exported themselves.
  const internal = new Map();
  while (queue.length > 0) {
    const sym = queue.shift();
    if (exportedTargets.has(sym) || publicKeys.has(keyOf(sym)) || internal.has(sym)) continue;
    const decls = (sym.declarations ?? []).filter((d) => isOurs(d.getSourceFile().fileName));
    internal.set(sym, decls);
    for (const decl of decls) queue.push(...referencedSymbols(checker, decl));
  }
  const internalEntries = [...internal.entries()]
    .map(([sym, decls]) => ({
      label: `${sym.getName()} (${relative(ROOT, decls[0].getSourceFile().fileName).split(sep).join("/")})`,
      decls,
    }))
    .sort((a, b) => a.label.localeCompare(b.label));
  if (internalEntries.length > 0) {
    lines.push("// ---- Not exported, but part of the API through the declarations above ----", "");
    for (const { label, decls } of internalEntries) {
      lines.push(`// ${label}`);
      for (const decl of decls) lines.push(declarationText(decl));
      lines.push("");
    }
  }
  return lines.join("\n");
}

const packages = PACKAGES.map(entriesOf);
const allFiles = packages.flatMap((p) => p.entries.map((e) => e.file));
for (const file of allFiles) {
  if (!existsSync(file)) {
    console.error(`api: ${relative(ROOT, file)} is missing. Run "npm run build" first.`);
    process.exit(1);
  }
}
const program = ts.createProgram(allFiles, {
  noEmit: true,
  skipLibCheck: true,
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
});
const publicKeys = allExportedKeys(program, allFiles);

const changed = [];
for (const { pkgName, entries } of packages) {
  const text = entries.map((entry) => surface(entry, program, publicKeys)).join("\n");
  // An inferred type that names an internal file (`import("./x.js").T`) is not
  // followed by the record and ties the API to a file layout: annotate it.
  const inferred = text.split("\n").filter((line) => /\bimport\(/.test(line));
  if (inferred.length > 0) {
    console.error(`api: ${pkgName} has types that point into internal files; give them an explicit type:`);
    for (const line of inferred) console.error(`api:   ${line.trim()}`);
    process.exit(1);
  }
  const file = join(OUT_DIR, `${pkgName.replace("@holdsend/", "")}.api.txt`);
  const before = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (before === text) continue;
  if (update) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`api: wrote ${relative(ROOT, file)}`);
  } else {
    changed.push(relative(ROOT, file));
  }
}

if (changed.length > 0) {
  console.error(`api: the public API differs from ${changed.join(", ")}.`);
  console.error('api: if the change is intended, run "node scripts/api-surface.mjs --update",');
  console.error("api: review the diff as an API change, and note it in CHANGELOG.md.");
  process.exit(1);
}
if (!update) console.log("api: public API matches the record in api/");
